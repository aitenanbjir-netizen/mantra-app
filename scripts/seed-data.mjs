function hashString(value) {
  let hash = 2166136261;
  for (let i = 0; i < value.length; i++) {
    hash ^= value.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

function mulberry32(seed) {
  let a = seed;
  return function random() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function clamp(value, min, max) {
  return Math.max(min, Math.min(max, value));
}

export function buildProdiRows() {
  const rows = [];

  for (const ptn of PTN) {
    const pool = POOLS[ptn.jenis].filter(
      (p) => !p.hanyaKedokteran || KEDOKTERAN.has(ptn.singkatan)
    );

    const acak = mulberry32(hashString(`pilih|${ptn.singkatan}`));
    const kandidat = pool.map((p) => ({
      ...p,
      skorPilih: (p.wajib ? 100 : 0) + p.pop * 50 + acak() * 20,
    }));

    const terpilih = kandidat
      .sort((a, b) => b.skorPilih - a.skorPilih)
      .slice(0, 10);

    for (const p of terpilih) {
      const rand = mulberry32(hashString(`${ptn.singkatan}|${p.nama}`));
      const pop = clamp(
        p.pop + (TOP_TIER.has(ptn.singkatan) ? 0.06 : 0),
        0,
        1
      );

      let dsnbp = Math.round(24 + rand() * 56 + pop * 20);
      if (ptn.jenis === 'vokasi') {
        dsnbp = Math.round(36 + rand() * 48);
      }
      const dsnbt = dsnbp + Math.round(8 + rand() * 32);

      const rasio = 0.11 - pop * 0.055 + rand() * 0.015;
      const base = Math.max(200, Math.round(dsnbp / rasio));

      const psnbp = [
        Math.round(base * (0.88 + rand() * 0.06)),
        Math.round(base * (0.94 + rand() * 0.06)),
        Math.round(base * (1.0 + rand() * 0.08)),
      ];

      const snbtBase = Math.round(base * (1.25 + rand() * 0.5));
      const psnbt = [
        Math.round(snbtBase * (0.9 + rand() * 0.08)),
        Math.round(snbtBase * (0.96 + rand() * 0.08)),
        Math.round(snbtBase * (1.02 + rand() * 0.08)),
      ];

      const medsnbp =
        Math.round(clamp(76 + pop * 10 + rand() * 3, 74, 90) * 10) / 10;
      const medsnbt = Math.round(clamp(540 + pop * 130 + rand() * 35, 520, 720));

      rows.push({
        singkatan: ptn.singkatan,
        nama: p.nama,
        rumpun:
          p.rumpun.toLowerCase() === 'vokasi'
            ? 'campuran'
            : p.rumpun.toLowerCase(),
        jenjang: ptn.jenis === 'vokasi' ? 'D4' : 'S1',
        butuhPortofolio: false,
        mapel: p.mapel,
        dsnbp,
        dsnbt,
        psnbp,
        psnbt,
        bobot: {
          rapor_umum: 0.5,
          mapel_pendukung: 0.3,
          prestasi: 0.1,
          tka: 0.1,
          median_snbp: medsnbp,
        },
        bobotSnbt: {
          PU: 0.15,
          PPU: 0.13,
          PBM: 0.13,
          PK: 0.15,
          LBI: 0.15,
          LBE: 0.14,
          PM: 0.15,
          median_snbt: medsnbt,
        },
        medsnbp,
        medsnbt,
      });
    }
  }

  return rows;
}
